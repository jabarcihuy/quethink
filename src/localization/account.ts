export function accountError(
  error: unknown,
  text: Record<keyof typeof en, string>,
): string {
  const code =
    typeof error === "object" && error !== null && "code" in error
      ? String(error.code)
      : error instanceof Error
        ? error.message
        : "";
  const keys: Record<string, keyof typeof en> = {
    invalid_credentials: "invalidCredentials",
    email_not_confirmed: "emailNotConfirmed",
    user_already_exists: "alreadyRegistered",
    weak_password: "invalidForm",
    AUTH_REQUIRED: "sessionExpired",
    PROFILE_INCOMPLETE: "profileIncomplete",
    VALIDATION_ERROR: "invalidValue",
    CLASS_CODE_INVALID: "invalidCode",
    CLASS_ARCHIVED: "classArchived",
    ALREADY_JOINED: "alreadyJoined",
    FORBIDDEN: "forbidden",
    TEACHER_REQUIRED: "forbidden",
    STUDENT_REQUIRED: "forbidden",
    RATE_LIMITED: "rateLimited",
    SUPABASE_NOT_CONFIGURED: "setupError",
    PHOTO_INVALID: "photoError",
    over_email_send_rate_limit: "rateLimited",
    over_request_rate_limit: "rateLimited",
  };
  return text[keys[code] ?? "error"];
}
